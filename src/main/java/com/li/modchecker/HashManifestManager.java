package com.li.modchecker;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.mojang.logging.LogUtils;
import net.minecraft.server.level.ServerPlayer;
import net.minecraftforge.fml.loading.FMLPaths;
import org.slf4j.Logger;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.OffsetDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Locale;
import java.util.Map;

/**
 * Loads / saves the SHA-256 hash manifest (generated from an admin client's report).
 */
public final class HashManifestManager {

    public static final String FILE_NAME = "modchecker-hashes.json";

    private static final Logger LOGGER = LogUtils.getLogger();
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().create();

    private static volatile HashManifestData current;
    private static volatile String loadError;

    private HashManifestManager() {
    }

    public static Path path() {
        return FMLPaths.CONFIGDIR.get().resolve(FILE_NAME);
    }

    public static HashManifestData current() {
        return current;
    }

    public static String loadError() {
        return loadError;
    }

    public static synchronized void load() {
        Path file = path();
        current = null;
        loadError = null;
        if (Files.notExists(file)) {
            LOGGER.warn("[ModChecker] Hash manifest not found: {} (generate it with /modchecker generate-hashes)", file);
            return;
        }
        try {
            if (!Files.isRegularFile(file)) {
                throw new IllegalStateException("hash manifest path is not a readable regular file");
            }
            if (Files.size(file) > 16L * 1024 * 1024) {
                throw new IllegalStateException("hash manifest exceeds 16 MiB");
            }
            String json = Files.readString(file, StandardCharsets.UTF_8);
            HashManifestData data = ManifestValidation.parse(GSON, json, HashManifestData.class);
            ManifestValidation.validate(data);
            current = data;
            LOGGER.info("[ModChecker] Loaded hash manifest {}: {} entries", file, data.mods.size());
        } catch (Exception e) {
            loadError = e.getMessage() == null ? e.getClass().getSimpleName() : e.getMessage();
            LOGGER.error("[ModChecker] Failed to load hash manifest {}: {}", file, e.toString());
        }
    }

    public static synchronized HashManifestData generate(ServerPlayer admin) {
        HashReportMessage report = HashVerificationManager.report(admin);
        if (report == null) {
            throw new IllegalStateException("No hash report received from " + admin.getGameProfile().getName()
                    + " yet (make sure the Mod Checker client companion is installed and wait a moment)");
        }
        HashManifestData data = new HashManifestData();
        data.generatedAt = DateTimeFormatter.ISO_OFFSET_DATE_TIME.format(OffsetDateTime.now());
        data.generatedBy = admin.getGameProfile().getName();
        for (Map.Entry<String, HashReportMessage.ClientMod> entry : report.mods.entrySet()) {
            HashReportMessage.ClientMod mod = entry.getValue();
            data.mods.put(entry.getKey(), new HashManifestData.ModHash(mod.sha256, mod.size, mod.name, mod.version));
        }

        ManifestValidation.validate(data);
        Path file = path();
        try {
            ManifestManager.writeJson(file, data, GSON);
        } catch (IOException e) {
            throw new IllegalStateException("Failed to write hash manifest " + file + ": " + e.getMessage(), e);
        }
        current = data;
        loadError = null;
        LOGGER.info("[ModChecker] Hash manifest generated by {}: {} entries -> {}",
                admin.getGameProfile().getName(), data.mods.size(), file);
        return data;
    }

    public static String shortHash(String hash) {
        if (hash == null || hash.isBlank()) {
            return "none";
        }
        String trimmed = hash.trim().toLowerCase(Locale.ROOT);
        return trimmed.length() <= 16 ? trimmed : trimmed.substring(0, 16);
    }
}
